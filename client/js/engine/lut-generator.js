/**
 * 3D LUT (.cube) Generator for RetroFilm
 * Converts current color grading, halation warmth transfer, tone curves, and filmic rolloff
 * into standard 33x33x33 3D LUT format compatible with Premiere Pro Lumetri Color and DaVinci Resolve.
 */

class FilmLUTGenerator {
    /**
     * Generates a 3D LUT .cube text content from current grading state.
     * @param {Object} state - Grading parameters
     * @param {number} size - LUT size (default 33)
     * @returns {string} .cube formatted text
     */
    static generateCubeLUT(state, size = 33) {
        let cubeText = `# Generated by RetroFilm Cinematic Suite for Premiere Pro\n`;
        cubeText += `# Title: ${state.presetName || "Custom Retro Grade"}\n`;
        cubeText += `LUT_3D_SIZE ${size}\n\n`;

        const step = 1.0 / (size - 1);

        for (let b = 0; b < size; b++) {
            for (let g = 0; g < size; g++) {
                for (let r = 0; r < size; r++) {
                    let red = r * step;
                    let green = g * step;
                    let blue = b * step;

                    // 1. Temperature & Tint Adjustment
                    if (state.tone) {
                        red += state.tone.temperature * 0.08;
                        blue -= state.tone.temperature * 0.08;
                        green += state.tone.tint * 0.06;

                        // 2. Saturation
                        const lum = red * 0.2126 + green * 0.7152 + blue * 0.0722;
                        red = lum + (red - lum) * state.tone.saturation;
                        green = lum + (green - lum) * state.tone.saturation;
                        blue = lum + (blue - lum) * state.tone.saturation;

                        // 3. Film S-Curve Contrast
                        const contrast = state.tone.contrast;
                        red = (red - 0.5) * contrast + 0.5;
                        green = (green - 0.5) * contrast + 0.5;
                        blue = (blue - 0.5) * contrast + 0.5;
                    }

                    // 4. Halation Warmth Transfer into Highlights
                    if (state.halation && state.halation.enabled && state.halation.intensity > 0) {
                        const lum = red * 0.2126 + green * 0.7152 + blue * 0.0722;
                        const hColor = state.halation.color || [1.0, 0.27, 0.05];
                        if (lum > state.halation.threshold) {
                            const bleed = (lum - state.halation.threshold) / (1.0 - state.halation.threshold);
                            const factor = bleed * state.halation.intensity * 0.25;
                            red += hColor[0] * factor;
                            green += hColor[1] * factor;
                            blue += hColor[2] * factor;
                        }
                    }

                    // 5. Highlight Soft Rolloff (Photochemical film shoulder)
                    red = Math.min(1.0, Math.max(0.0, red));
                    green = Math.min(1.0, Math.max(0.0, green));
                    blue = Math.min(1.0, Math.max(0.0, blue));

                    cubeText += `${red.toFixed(6)} ${green.toFixed(6)} ${blue.toFixed(6)}\n`;
                }
            }
        }

        return cubeText;
    }

    /**
     * Triggers browser / CEP download of the generated .cube LUT.
     */
    static exportAndDownload(state, filename = "RetroFilm_Grade.cube") {
        const cubeContent = this.generateCubeLUT(state, 33);
        const blob = new Blob([cubeContent], { type: "text/plain;charset=utf-8" });
        const url = URL.createObjectURL(blob);
        const a = document.createElement("a");
        a.href = url;
        a.download = filename;
        document.body.appendChild(a);
        a.click();
        document.body.removeChild(a);
        URL.revokeObjectURL(url);
    }
}
